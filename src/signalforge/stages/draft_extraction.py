"""Deterministic drafting logic (FR-07/FR-08): template choice, span checks, claim
status, the publish gate and the review summary. No LLM calls, no DB.
"""

import re
import urllib.parse
from collections.abc import Sequence
from dataclasses import dataclass

from signalforge.core.artifacts.article import ArticleBody, ArticleClaim, ArticleTemplate
from signalforge.core.artifacts.research import (
    ClaimStatus,
    ResearchClaim,
    ResearchDocument,
    ResearchPackage,
)
from signalforge.stages.research_extraction import span_exists

PAPER_SOURCE_TYPE = "paper"
BLOG_SOURCE_TYPE = "blog"
COMPARISON_TAG = "comparison"
RELEASE_TAGS = frozenset({"release", "launch"})
_RELEASE_TITLE = re.compile(
    r"\b(released?|releases|launch(es|ed)?|announc(es|ed|ing)|introducing)\b", re.IGNORECASE
)

# Word-count bands from the 2026-09-27 template table; the publish gate enforces them.
LENGTH_BANDS: dict[ArticleTemplate, tuple[int, int]] = {
    ArticleTemplate.NEWS_BRIEF: (250, 400),
    ArticleTemplate.EXPLAINER: (700, 1000),
    ArticleTemplate.PAPER_BREAKDOWN: (500, 800),
    ArticleTemplate.COMPARISON: (600, 900),
}

_EM_DASH = "\u2014"
# An en dash between spaces is a dash; inside "2020\u20132024" it is a range and allowed.
_EN_DASH_AS_DASH = re.compile(r"\s\u2013\s")
# First-person/experiential and AI-authorship phrasing (2026-09-27 style rules).
_BANNED_PHRASES = re.compile(
    r"\b(as an ai|as a language model|i tested|we tested|i ran|we ran|i tried|we tried"
    r"|in my experience|in our testing|generated by ai|written by ai|ai-generated"
    r"|this article was (generated|written by))\b",
    re.IGNORECASE,
)


def select_template(
    *, source_type: str, card_format: str, topics: Sequence[str], title: str
) -> ArticleTemplate:
    """First match wins: paper, then comparison, then release/launch, else explainer.

    A post from a lab or vendor blog (the RSS sources) counts as a release signal: those
    feeds announce models, results and launches, and rarely use the words themselves.
    """
    tags = {topic.strip().lower() for topic in topics}
    if source_type == PAPER_SOURCE_TYPE:
        return ArticleTemplate.PAPER_BREAKDOWN
    if card_format == COMPARISON_TAG or COMPARISON_TAG in tags:
        return ArticleTemplate.COMPARISON
    if source_type == BLOG_SOURCE_TYPE or tags & RELEASE_TAGS or _RELEASE_TITLE.search(title):
        return ArticleTemplate.NEWS_BRIEF
    return ArticleTemplate.EXPLAINER


def span_documents(claim: ArticleClaim, documents: Sequence[ResearchDocument]) -> frozenset[int]:
    """Indices of the cited documents whose stored text contains the claim's span verbatim."""
    return frozenset(
        index
        for index in claim.document_indices
        if index < len(documents) and span_exists(claim.evidence_span, documents[index].text)
    )


def flagged_spans(package: ResearchPackage) -> frozenset[str]:
    """Evidence spans of research claims that FR-06 flagged as a likely disagreement."""
    gaps = package.gaps_and_disagreements
    return frozenset(c.evidence_span for c in package.claims if gaps and f"'{c.text}'" in gaps)


def is_conflicting(claim: ArticleClaim, flagged: frozenset[str]) -> bool:
    span = claim.evidence_span.strip()
    return any(span in other or other in span for other in flagged)


def _host(url: str) -> str:
    return urllib.parse.urlsplit(url).hostname or url


def independent_sources(span_docs: frozenset[int], documents: Sequence[ResearchDocument]) -> int:
    """Distinct hosts among the documents whose text holds the span."""
    return len({_host(documents[i].url) for i in span_docs})


def assign_status(
    *,
    span_docs: frozenset[int],
    judge_supported: bool,
    conflicting: bool,
    documents: Sequence[ResearchDocument],
) -> ClaimStatus:
    """PRD Sec. 11: verified, supported, uncertain, conflicting, unverified."""
    if not span_docs:
        return ClaimStatus.UNVERIFIED
    if conflicting:
        return ClaimStatus.CONFLICTING
    if not judge_supported:
        return ClaimStatus.UNCERTAIN
    has_primary = any(documents[i].is_primary for i in span_docs)
    if has_primary or independent_sources(span_docs, documents) >= 2:
        return ClaimStatus.VERIFIED
    return ClaimStatus.SUPPORTED


def _reader_text(body: ArticleBody) -> list[str]:
    parts = [body.title, body.dek, body.cover.alt, body.cover.credit or ""]
    for section in body.sections:
        parts.append(section.heading)
        parts.extend(section.paragraphs)
    return parts


def word_count(body: ArticleBody) -> int:
    return sum(len(p.split()) for s in body.sections for p in s.paragraphs) + len(body.dek.split())


def publish_gate(body: ArticleBody, template: ArticleTemplate) -> list[str]:
    """Return the gate failures; empty means the draft passes. Fails closed."""
    failures: list[str] = []
    text = "\n".join(_reader_text(body))
    if _EM_DASH in text or _EN_DASH_AS_DASH.search(text):
        failures.append("contains an em dash or an en dash used as a dash")
    phrase = _BANNED_PHRASES.search(text)
    if phrase:
        failures.append(f"contains banned authorship phrasing: '{phrase.group(0)}'")
    low, high = LENGTH_BANDS[template]
    words = word_count(body)
    if not low <= words <= high:
        failures.append(f"length {words} words is outside the {template.value} band {low}-{high}")
    return failures


@dataclass(frozen=True)
class ClaimCheck:
    claim: ArticleClaim
    span_ok: bool
    judge_supported: bool
    single_source: bool


def build_review_summary(
    checks: Sequence[ClaimCheck], gate_failures: Sequence[str], notes: Sequence[str] = ()
) -> str:
    """Plain-text risk summary, assembled mechanically for the editor."""
    lines: list[str] = []
    for index, check in enumerate(checks):
        label = f"Claim {index} ({check.claim.status.value}): {check.claim.text}"
        if check.claim.status in {
            ClaimStatus.UNCERTAIN,
            ClaimStatus.CONFLICTING,
            ClaimStatus.UNVERIFIED,
        }:
            lines.append(f"Needs attention. {label}")
        elif check.single_source:
            lines.append(f"Single source. {label}")
        if check.judge_supported and not check.span_ok:
            lines.append(f"Judge supports claim {index} but its quote was not found in the source.")
        if check.span_ok and not check.judge_supported:
            lines.append(f"Quote for claim {index} found, but the judge does not confirm it.")
    lines.extend(f"Publish gate: {failure}." for failure in gate_failures)
    lines.extend(f"Check: {note}" for note in notes)
    return "\n".join(lines)


_NUMBER = re.compile(r"\d[\d,]*(?:\.\d+)?")
# Capitalised or all-caps words and hyphenated product names, e.g. "Nemotron", "IMO", "GPT-4o".
_NAME = re.compile(r"[A-Z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)*")
_SNIPPET_CHARS = 80


def _numbers(text: str) -> set[str]:
    return {m.group(0).replace(",", "").rstrip(".") for m in _NUMBER.finditer(text)}


def claim_support(
    claims: Sequence[ResearchClaim], ids: Sequence[int], documents: Sequence[ResearchDocument]
) -> str:
    """Text a sentence citing ``ids`` may draw numbers and names from.

    The claim, its quote and the document context around the quote: the same excerpt the
    writer was shown and the judge will see, so the three checks agree on what is evidence.
    """
    return " ".join(f"{claims[i].text} {evidence_window(claims[i], documents)}" for i in ids)


def sentence_problems(text: str, ids: Sequence[int], support: str) -> list[str]:
    """Deterministic grounding failures for one sentence. Empty means it passes.

    A sentence must cite at least one claim, and every number in it must appear in the
    cited claims or their quotes. A model can still misstate a fact without a number, which
    is what the judge and ``unfamiliar_names`` are for.
    """
    snippet = text if len(text) <= _SNIPPET_CHARS else text[:_SNIPPET_CHARS] + "..."
    if not ids:
        return [f"uncited sentence: '{snippet}'"]
    missing = sorted(_numbers(text) - _numbers(support))
    if missing:
        return [f"number(s) {', '.join(missing)} not in the cited claims: '{snippet}'"]
    return []


def unfamiliar_names(text: str, support: str) -> list[str]:
    """Names in ``text`` (not at sentence start) that the cited claims never mention."""
    lowered = support.lower()
    words = _NAME.findall(text)
    first = text.split(maxsplit=1)[0].strip("\"'(") if text.split() else ""
    return sorted({w for w in words if len(w) >= 3 and w != first and w.lower() not in lowered})


def evidence_window(
    claim: ResearchClaim, documents: Sequence[ResearchDocument], radius: int = 300
) -> str:
    """The claim's quote with ``radius`` chars of its document around it, for context.

    Falls back to the bare quote when no cited document holds it verbatim.
    """
    span = claim.evidence_span.strip()
    for index in claim.document_indices:
        if index >= len(documents):
            continue
        text = documents[index].text
        at = text.find(span) if span else -1
        if at >= 0:
            return text[max(0, at - radius) : at + len(span) + radius]
    return span
